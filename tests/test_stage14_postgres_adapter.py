class TestPhase14PostgresAdapter(unittest.TestCase):
    def setUp(self):
        self.temp_db_fd, self.temp_db_path = tempfile.mkstemp(suffix='.db')
        init_database(self.temp_db_path)

    def tearDown(self):
        try:
            os.close(self.temp_db_fd)
            if os.path.exists(self.temp_db_path):
                os.unlink(self.temp_db_path)
        except OSError:
            pass

    def test_01_schema_postgres_ddl_structure(self):
        """Verify schema_postgres.sql contains all 14 tables with PostgreSQL-compatible types."""
        self.assertTrue(os.path.exists(SCHEMA_POSTGRES_PATH), "schema_postgres.sql file must exist")
        with open(SCHEMA_POSTGRES_PATH, 'r', encoding='utf-8') as f:
            ddl = f.read()

        expected_tables = [
            'users', 'orders', 'delivery_inspections', 'inspection_confirmations',
            'audit_events', 'inspection_corrections', 'plants', 'deal_agreements',
            'agreement_approvals', 'order_items', 'invoices', 'invoice_items',
            'payments', 'payment_allocations'
        ]
        for tbl in expected_tables:
            self.assertRegex(ddl, rf"CREATE TABLE IF NOT EXISTS {tbl}\b", f"Missing table {tbl} in PostgreSQL schema")

        # Verify PostgreSQL-specific identity sequences and numeric types
        self.assertIn("GENERATED BY DEFAULT AS IDENTITY", ddl)
        self.assertIn("NUMERIC(12, 2)", ddl)
        self.assertIn("TIMESTAMPTZ", ddl)
        self.assertNotIn("AUTOINCREMENT", ddl, "AUTOINCREMENT is SQLite-specific and must not appear in PostgreSQL DDL")
        self.assertNotIn("PRAGMA", ddl, "PRAGMA statements must not appear in PostgreSQL DDL")

    def test_02_sql_placeholder_translation_edge_cases(self):
        """Verify translate_sql_placeholders correctly replaces unquoted ? with %s."""
        # 1. Simple queries
        q1 = "SELECT * FROM users WHERE id = ?"
        self.assertEqual(translate_sql_placeholders(q1), "SELECT * FROM users WHERE id = %s")

        q2 = "INSERT INTO plants (common_name, category, unit_price) VALUES (?, ?, ?)"
        self.assertEqual(translate_sql_placeholders(q2), "INSERT INTO plants (common_name, category, unit_price) VALUES (%s, %s, %s)")

        # 2. String literal containing ? (must NOT be replaced)
        q3 = "SELECT * FROM audit_events WHERE justification = 'Is this delivered?' AND actor_user_id = ?"
        self.assertEqual(translate_sql_placeholders(q3), "SELECT * FROM audit_events WHERE justification = 'Is this delivered?' AND actor_user_id = %s")

        # 3. String literal with escaped single quote and question mark
        q4 = "INSERT INTO audit_events (notes, user_id) VALUES ('Supplier''s note: Ready?', ?)"
        self.assertEqual(translate_sql_placeholders(q4), "INSERT INTO audit_events (notes, user_id) VALUES ('Supplier''s note: Ready?', %s)")

        # 4. Double quoted column identifier containing ?
        q5 = 'SELECT "is_questionable?" FROM flags WHERE id = ?'
        self.assertEqual(translate_sql_placeholders(q5), 'SELECT "is_questionable?" FROM flags WHERE id = %s')

        # 5. Query without any placeholders
        q6 = "SELECT COUNT(*) FROM orders WHERE status = 'CONFIRMED'"
        self.assertEqual(translate_sql_placeholders(q6), q6)

    def test_03_extract_insert_target_table(self):
        """Verify extract_insert_target_table identifies destination tables."""
        self.assertEqual(extract_insert_target_table("INSERT INTO plants (common_name) VALUES (?)"), "plants")
        self.assertEqual(extract_insert_target_table("  insert  into   deal_agreements \n (agreement_ref) VALUES (?)"), "deal_agreements")
        self.assertEqual(extract_insert_target_table("INSERT INTO public.order_items (order_id) VALUES (?)"), "order_items")
        self.assertIsNone(extract_insert_target_table("SELECT * FROM plants WHERE id = 1"))
        self.assertIsNone(extract_insert_target_table("UPDATE orders SET status = 'DELIVERED' WHERE id = ?"))

    def test_04_postgres_row_mapping_behavior(self):
        """Verify PostgresRow supports dictionary access, index access, and dict() conversion."""
        cols = ['id', 'username', 'role', 'business_name', 'created_at']
        vals = [2, 'nursery_amit', 'NURSERY', 'Green Meadows Landscape Nursery', '2026-10-16 10:00:00']
        row = PostgresRow(cols, vals)

        # 1. Key-based access
        self.assertEqual(row['id'], 2)
        self.assertEqual(row['username'], 'nursery_amit')
        self.assertEqual(row['role'], 'NURSERY')

        # 2. Case-insensitive key fallback
        self.assertEqual(row['ROLE'], 'NURSERY')
        self.assertEqual(row['Business_Name'], 'Green Meadows Landscape Nursery')

        # 3. Index-based access
        self.assertEqual(row[0], 2)
        self.assertEqual(row[1], 'nursery_amit')
        self.assertEqual(row[3], 'Green Meadows Landscape Nursery')

        # 4. dict(row) mapping compatibility
        d = dict(row)
        self.assertIsInstance(d, dict)
        self.assertEqual(d['username'], 'nursery_amit')
        self.assertEqual(len(d), 5)

        # 5. .get() method
        self.assertEqual(row.get('username'), 'nursery_amit')
        self.assertEqual(row.get('nonexistent_col', 'default_val'), 'default_val')

        # 6. Containment check ('col' in row)
        self.assertIn('username', row)
        self.assertIn('USERNAME', row)
        self.assertNotIn('unknown_column', row)

        # 7. KeyError on missing key
        with self.assertRaises(KeyError):
            _ = row['does_not_exist']

    def test_05_mock_postgres_cursor_adapter(self):
        """Verify PostgresCursorAdapter translates queries, appends RETURNING id, and extracts lastrowid."""
        mock_raw_cursor = MagicMock()
        mock_raw_cursor.description = [('id',), ('common_name',)]
        mock_raw_cursor.fetchone.return_value = (42,)

        adapter = PostgresCursorAdapter(mock_raw_cursor)

        # 1. INSERT on autoincrement table (plants) must append RETURNING id
        adapter.execute("INSERT INTO plants (common_name, unit_price) VALUES (?, ?);", ('Rose', 150.0))
        executed_sql = mock_raw_cursor.execute.call_args[0][0]
        executed_params = mock_raw_cursor.execute.call_args[0][1]

        self.assertIn("RETURNING id", executed_sql)
        self.assertIn("%s, %s", executed_sql)
        self.assertEqual(executed_params, ('Rose', 150.0))
        self.assertEqual(adapter.lastrowid, 42)

        # 2. INSERT on string-PK table (orders) must NOT append RETURNING id
        adapter.execute("INSERT INTO orders (id, variety) VALUES (?, ?);", ('ORD-999', 'Tulip'))
        order_sql = mock_raw_cursor.execute.call_args[0][0]
        self.assertNotIn("RETURNING id", order_sql)
        self.assertIsNone(adapter.lastrowid)

        # 3. SELECT query must not append RETURNING id
        mock_raw_cursor.fetchone.return_value = (1, 'Areca Palm')
        adapter.execute("SELECT id, common_name FROM plants WHERE id = ?", (1,))
        sel_sql = mock_raw_cursor.execute.call_args[0][0]
        self.assertNotIn("RETURNING id", sel_sql)
        self.assertIn("WHERE id = %s", sel_sql)

        # Fetch returns PostgresRow
        res = adapter.fetchone()
        self.assertIsInstance(res, PostgresRow)
        self.assertEqual(res['id'], 1)
        self.assertEqual(res['common_name'], 'Areca Palm')

    def test_06_mock_postgres_connection_adapter(self):
        """Verify PostgresConnectionAdapter executes queries and supports transaction context."""
        mock_raw_conn = MagicMock()
        mock_raw_cur = MagicMock()
        mock_raw_conn.cursor.return_value = mock_raw_cur
        mock_raw_cur.description = [('count',)]
        mock_raw_cur.fetchone.return_value = (10,)

        conn_adapter = PostgresConnectionAdapter(mock_raw_conn)

        # conn.execute direct convenience method
        res = conn_adapter.execute("SELECT COUNT(*) FROM users WHERE role = ?", ('SUPPLIER',))
        self.assertIsInstance(res, PostgresCursorAdapter)
        mock_raw_cur.execute.assert_called_once()
        self.assertIn("%s", mock_raw_cur.execute.call_args[0][0])

        # Transaction context manager: commit on success
        with conn_adapter:
            conn_adapter.execute("UPDATE plants SET stock_qty = ? WHERE id = ?", (50, 1))
        mock_raw_conn.commit.assert_called_once()

        # Transaction context manager: rollback on exception
        try:
            with conn_adapter:
                raise ValueError("Simulated transaction failure")
        except ValueError:
            pass
        mock_raw_conn.rollback.assert_called_once()

    def test_07_dialect_resolution_and_defaults(self):
        """Verify dialect detection defaults to SQLite and recognizes PostgreSQL connection strings."""
        # 1. Default without configuration -> SQLite
        self.assertEqual(get_active_dialect(None), 'sqlite')

        # 2. SQLite file path -> SQLite
        self.assertEqual(get_active_dialect('supplier_platform/data/florachain.db'), 'sqlite')
        self.assertEqual(get_active_dialect(':memory:'), 'sqlite')

        # 3. PostgreSQL connection strings -> PostgreSQL
        self.assertTrue(is_postgres_url('postgresql://user:pass@localhost:5432/florachain_db'))
        self.assertTrue(is_postgres_url('postgres://user:pass@localhost:5432/florachain_db'))
        self.assertFalse(is_postgres_url('data/florachain.db'))
        self.assertFalse(is_postgres_url(None))

        self.assertEqual(get_active_dialect('postgresql://postgres:postgres@localhost:5432/testdb'), 'postgresql')
        self.assertEqual(get_active_dialect('postgres://postgres:postgres@localhost:5432/testdb'), 'postgresql')

    def test_08_sqlite_default_fallback_operational_continuity(self):
        """Verify that SQLite connection functions normally under the adapter engine."""
        conn = get_connection(self.temp_db_path)
        try:
            # Table queries and rows work as expected
            users = conn.execute("SELECT id, username, role FROM users ORDER BY id;").fetchall()
            self.assertGreaterEqual(len(users), 1)
            first_user = users[0]
            self.assertEqual(first_user['username'], 'supplier_rajesh')
            self.assertEqual(first_user[0], 1)

            # Insert and lastrowid
            cur = conn.execute(
                """INSERT INTO audit_events (event_type, order_id, actor_role, after_state_json)
                   VALUES (?, ?, ?, ?)""",
                ('ADAPTER_TEST', 'ORD-TEST-14', 'SYSTEM', '{}')
            )
            self.assertIsNotNone(cur.lastrowid)
            self.assertGreaterEqual(cur.lastrowid, 1)
        finally:
            conn.close()



-- FloraChain B2B — PostgreSQL Relational Schema
-- Phase 14: Relational PostgreSQL Schema with Identity Sequences, Fixed-Point Decimal, and Foreign Keys

-- 1. Users & Roles
CREATE TABLE IF NOT EXISTS users (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(255) UNIQUE NOT NULL,
    email VARCHAR(255) UNIQUE NOT NULL,
    password_hash VARCHAR(255) NOT NULL,
    role VARCHAR(20) NOT NULL CHECK(role IN ('SUPPLIER', 'NURSERY', 'ADMIN')),
    business_name VARCHAR(255) NOT NULL,
    created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
);

-- 2. Wholesale Plant Orders
CREATE TABLE IF NOT EXISTS orders (
    id VARCHAR(64) PRIMARY KEY,
    supplier_user_id INTEGER NOT NULL REFERENCES users(id),
    nursery_user_id INTEGER NOT NULL REFERENCES users(id),
    variety VARCHAR(255) NOT NULL,
    ordered_qty INTEGER NOT NULL CHECK(ordered_qty > 0),
    unit_price NUMERIC(12, 2) NOT NULL CHECK(unit_price > 0),
    truck_no VARCHAR(100) NOT NULL DEFAULT 'TBD',
    driver_info VARCHAR(255) NOT NULL DEFAULT 'TBD',
    status VARCHAR(50) NOT NULL CHECK(status IN (
        'DRAFT', 'CONFIRMED', 'STAGING', 'DISPATCHED',
        'INSPECTED_PENDING_CONFIRMATION', 'DELIVERED', 'LOCKED_VERIFIED', 'CANCELLED'
    )),
    loaded_at TIMESTAMPTZ NULL,
    loading_notes TEXT DEFAULT '',
    created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
);

-- 3. Delivery Physical Inspections
CREATE TABLE IF NOT EXISTS delivery_inspections (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id VARCHAR(64) UNIQUE NOT NULL REFERENCES orders(id),
    delivered_qty INTEGER NOT NULL CHECK(delivered_qty >= 0),
    sound_qty INTEGER NOT NULL CHECK(sound_qty >= 0),
    damaged_qty INTEGER NOT NULL CHECK(damaged_qty >= 0),
    damage_pct NUMERIC(5, 2) NOT NULL CHECK(damage_pct >= 0.0),
    damage_notes TEXT DEFAULT '',
    has_mismatch SMALLINT NOT NULL CHECK(has_mismatch IN (0, 1)),
    mismatch_diff INTEGER NOT NULL,
    status VARCHAR(50) NOT NULL CHECK(status IN ('DRAFT', 'PENDING_SUPPLIER_CONFIRMATION', 'LOCKED_VERIFIED', 'CORRECTED')),
    is_locked SMALLINT NOT NULL DEFAULT 0 CHECK(is_locked IN (0, 1)),
    locked_at TIMESTAMPTZ NULL,
    created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
);

-- 4. Independent Party Counter-Signatures (Dual Confirmation)
CREATE TABLE IF NOT EXISTS inspection_confirmations (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    inspection_id INTEGER NOT NULL REFERENCES delivery_inspections(id) ON DELETE CASCADE,
    party_role VARCHAR(20) NOT NULL CHECK(party_role IN ('NURSERY', 'SUPPLIER')),
    user_id INTEGER NOT NULL REFERENCES users(id),
    confirmed_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
    ip_address VARCHAR(45) NOT NULL DEFAULT '127.0.0.1',
    signature_note TEXT DEFAULT '',
    CONSTRAINT uq_party_confirmation UNIQUE(inspection_id, party_role)
);

-- 5. Append-Only Audit Ledger
CREATE TABLE IF NOT EXISTS audit_events (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_type VARCHAR(100) NOT NULL,
    order_id VARCHAR(64) NOT NULL,
    actor_user_id INTEGER REFERENCES users(id),
    actor_role VARCHAR(50) NOT NULL,
    before_state_json TEXT NULL,
    after_state_json TEXT NOT NULL,
    justification TEXT DEFAULT '',
    ip_address VARCHAR(45) NOT NULL DEFAULT '127.0.0.1',
    created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
);

-- 6. Administrative Corrections Workflow
CREATE TABLE IF NOT EXISTS inspection_corrections (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    inspection_id INTEGER NOT NULL REFERENCES delivery_inspections(id),
    requested_by INTEGER NOT NULL REFERENCES users(id),
    approved_by INTEGER NULL REFERENCES users(id),
    original_sound_qty INTEGER NOT NULL,
    original_damaged_qty INTEGER NOT NULL,
    corrected_sound_qty INTEGER NOT NULL,
    corrected_damaged_qty INTEGER NOT NULL,
    reason TEXT NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'PENDING' CHECK(status IN ('PENDING', 'APPROVED', 'REJECTED')),
    created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
    resolved_at TIMESTAMPTZ NULL
);

-- 7. Wholesale Plant Catalog & Inventory
CREATE TABLE IF NOT EXISTS plants (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    common_name VARCHAR(255) NOT NULL,
    botanical_name VARCHAR(255) DEFAULT '',
    category VARCHAR(50) NOT NULL CHECK(category IN (
        'INDOOR', 'OUTDOOR', 'FLOWERING', 'ORNAMENTAL',
        'TREE', 'PALM', 'SUCCULENT', 'CLIMBER',
        'SEASONAL', 'MEDICINAL', 'FRUIT', 'OTHER'
    )),
    container_size VARCHAR(100) NOT NULL,
    unit VARCHAR(50) NOT NULL DEFAULT 'plant' CHECK(unit IN ('plant', 'tray', 'bag', 'pot', 'bundle')),
    unit_price NUMERIC(12, 2) NOT NULL CHECK(unit_price > 0),
    stock_qty INTEGER NOT NULL DEFAULT 0 CHECK(stock_qty >= 0),
    min_order_qty INTEGER NOT NULL DEFAULT 1 CHECK(min_order_qty >= 1),
    description TEXT DEFAULT '',
    status VARCHAR(50) NOT NULL DEFAULT 'ACTIVE' CHECK(status IN ('ACTIVE', 'DISCONTINUED', 'OUT_OF_STOCK')),
    supplier_user_id INTEGER NOT NULL REFERENCES users(id),
    created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
);

-- 8. Digital Deal Agreements & Payment Terms
CREATE TABLE IF NOT EXISTS deal_agreements (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    agreement_ref VARCHAR(64) UNIQUE NOT NULL,
    order_id VARCHAR(64) NOT NULL REFERENCES orders(id),
    version INTEGER NOT NULL DEFAULT 1,
    supplier_user_id INTEGER NOT NULL REFERENCES users(id),
    nursery_user_id INTEGER NOT NULL REFERENCES users(id),
    plant_variety VARCHAR(255) NOT NULL,
    quantity INTEGER NOT NULL CHECK(quantity > 0),
    unit_price NUMERIC(12, 2) NOT NULL CHECK(unit_price > 0),
    total_order_value NUMERIC(12, 2) NOT NULL CHECK(total_order_value > 0),
    advance_percentage NUMERIC(5, 2) NOT NULL CHECK(advance_percentage >= 0 AND advance_percentage <= 100),
    advance_amount NUMERIC(12, 2) NOT NULL CHECK(advance_amount >= 0),
    balance_amount NUMERIC(12, 2) NOT NULL CHECK(balance_amount >= 0),
    payment_due_date DATE NOT NULL,
    payment_period_days INTEGER DEFAULT 10 CHECK(payment_period_days >= 0),
    interest_rate_pct NUMERIC(5, 2) NOT NULL DEFAULT 0.0 CHECK(interest_rate_pct >= 0),
    interest_calculation_basis VARCHAR(50) DEFAULT 'ANNUAL_SIMPLE' CHECK(interest_calculation_basis IN ('ANNUAL_SIMPLE', 'MONTHLY_SIMPLE', 'DAILY_SIMPLE', 'NONE')),
    interest_grace_period_days INTEGER DEFAULT 0 CHECK(interest_grace_period_days >= 0),
    notes TEXT DEFAULT '',
    status VARCHAR(50) NOT NULL CHECK(status IN ('DRAFT', 'PENDING_COUNTERPARTY_APPROVAL', 'AGREED', 'CANCELLED')),
    created_by_user_id INTEGER NOT NULL REFERENCES users(id),
    agreed_at TIMESTAMPTZ NULL,
    created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
);

-- 9. Independent Party Approvals for Deal Agreements
CREATE TABLE IF NOT EXISTS agreement_approvals (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    agreement_id INTEGER NOT NULL REFERENCES deal_agreements(id) ON DELETE CASCADE,
    party_role VARCHAR(20) NOT NULL CHECK(party_role IN ('SUPPLIER', 'NURSERY')),
    user_id INTEGER NOT NULL REFERENCES users(id),
    approval_type VARCHAR(50) NOT NULL DEFAULT 'IN_APP_CLICK' CHECK(approval_type IN ('IN_APP_CLICK', 'RECORDED_CONSENT')),
    terms_snapshot_json TEXT NOT NULL,
    notes TEXT DEFAULT '',
    approved_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
    ip_address VARCHAR(45) NOT NULL DEFAULT '127.0.0.1',
    CONSTRAINT uq_agreement_party UNIQUE(agreement_id, party_role)
);

-- 10. Order Line Items (Wholesale Plant Items per Order)
CREATE TABLE IF NOT EXISTS order_items (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id VARCHAR(64) NOT NULL REFERENCES orders(id) ON DELETE CASCADE,
    plant_id INTEGER REFERENCES plants(id),
    variety VARCHAR(255) NOT NULL,
    quantity INTEGER NOT NULL CHECK(quantity > 0),
    unit_price NUMERIC(12, 2) NOT NULL CHECK(unit_price > 0),
    line_total NUMERIC(12, 2) NOT NULL CHECK(line_total > 0),
    loaded_qty INTEGER NOT NULL DEFAULT 0 CHECK(loaded_qty >= 0 AND loaded_qty <= quantity),
    delivered_qty INTEGER NULL,
    sound_qty INTEGER NULL,
    damaged_qty INTEGER DEFAULT 0,
    created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
);

-- 11. Wholesale Invoices (Verified Delivery Invoicing)
CREATE TABLE IF NOT EXISTS invoices (
    id VARCHAR(64) PRIMARY KEY,
    invoice_number VARCHAR(64) UNIQUE NOT NULL,
    order_id VARCHAR(64) NOT NULL REFERENCES orders(id),
    supplier_user_id INTEGER NOT NULL REFERENCES users(id),
    nursery_user_id INTEGER NOT NULL REFERENCES users(id),
    inspection_id INTEGER REFERENCES delivery_inspections(id),
    invoice_date DATE NOT NULL,
    due_date DATE NULL,
    currency VARCHAR(10) NOT NULL DEFAULT 'INR',
    subtotal NUMERIC(12, 2) NOT NULL CHECK(subtotal >= 0),
    tax_rate_pct NUMERIC(5, 2) NOT NULL DEFAULT 0.0 CHECK(tax_rate_pct >= 0),
    tax_amount NUMERIC(12, 2) NOT NULL DEFAULT 0.0 CHECK(tax_amount >= 0),
    discount_amount NUMERIC(12, 2) NOT NULL DEFAULT 0.0 CHECK(discount_amount >= 0),
    total_amount NUMERIC(12, 2) NOT NULL CHECK(total_amount >= 0),
    total_quantity INTEGER NOT NULL CHECK(total_quantity >= 0),
    status VARCHAR(20) NOT NULL DEFAULT 'ISSUED' CHECK(status IN ('DRAFT', 'ISSUED', 'CANCELLED')),
    damage_billing_policy VARCHAR(50) DEFAULT 'CREDITED_EXCLUDED',
    interest_rate_pct NUMERIC(5, 2) NOT NULL DEFAULT 0.0 CHECK(interest_rate_pct >= 0),
    interest_calculation_basis VARCHAR(50) NOT NULL DEFAULT 'ANNUAL_SIMPLE' CHECK(interest_calculation_basis IN ('ANNUAL_SIMPLE', 'MONTHLY_SIMPLE', 'DAILY_SIMPLE', 'NONE')),
    interest_grace_period_days INTEGER NOT NULL DEFAULT 0 CHECK(interest_grace_period_days >= 0),
    agreement_ref VARCHAR(64) NULL,
    notes TEXT DEFAULT '',
    terms_snapshot_json TEXT NULL,
    created_by_user_id INTEGER NOT NULL REFERENCES users(id),
    created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
);

-- 12. Wholesale Invoice Line Items (Frozen Snapshot of Invoiced Plant Varieties)
CREATE TABLE IF NOT EXISTS invoice_items (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    invoice_id VARCHAR(64) NOT NULL REFERENCES invoices(id) ON DELETE CASCADE,
    order_item_id INTEGER REFERENCES order_items(id),
    plant_id INTEGER REFERENCES plants(id),
    variety VARCHAR(255) NOT NULL,
    botanical_name VARCHAR(255) DEFAULT '',
    category VARCHAR(50) DEFAULT '',
    container_size VARCHAR(100) DEFAULT '',
    unit VARCHAR(50) NOT NULL DEFAULT 'plant',
    ordered_qty INTEGER NOT NULL CHECK(ordered_qty >= 0),
    delivered_qty INTEGER NOT NULL CHECK(delivered_qty >= 0),
    sound_qty INTEGER NOT NULL CHECK(sound_qty >= 0),
    damaged_qty INTEGER NOT NULL DEFAULT 0 CHECK(damaged_qty >= 0),
    billable_qty INTEGER NOT NULL CHECK(billable_qty >= 0),
    unit_price NUMERIC(12, 2) NOT NULL CHECK(unit_price > 0),
    damaged_unit_price NUMERIC(12, 2) NOT NULL DEFAULT 0.0 CHECK(damaged_unit_price >= 0),
    line_total NUMERIC(12, 2) NOT NULL CHECK(line_total >= 0),
    notes TEXT DEFAULT '',
    created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
);

-- 13. Wholesale Payments (Payment Management)
CREATE TABLE IF NOT EXISTS payments (
    id VARCHAR(64) PRIMARY KEY,
    payment_number VARCHAR(64) UNIQUE NOT NULL,
    invoice_id VARCHAR(64) NULL REFERENCES invoices(id),
    order_id VARCHAR(64) NULL REFERENCES orders(id),
    supplier_user_id INTEGER NOT NULL REFERENCES users(id),
    nursery_user_id INTEGER NOT NULL REFERENCES users(id),
    amount NUMERIC(12, 2) NOT NULL CHECK(amount > 0),
    unallocated_amount NUMERIC(12, 2) NOT NULL DEFAULT 0.0 CHECK(unallocated_amount >= 0),
    payment_date DATE NOT NULL,
    payment_method VARCHAR(50) NOT NULL CHECK(payment_method IN ('BANK_TRANSFER', 'UPI', 'CHEQUE', 'CASH', 'OTHER')),
    reference_number VARCHAR(100) NOT NULL,
    payment_type VARCHAR(50) NOT NULL DEFAULT 'INVOICE_PAYMENT' CHECK(payment_type IN ('INVOICE_PAYMENT', 'ADVANCE_PAYMENT')),
    status VARCHAR(20) NOT NULL DEFAULT 'RECORDED' CHECK(status IN ('RECORDED', 'REVERSED')),
    notes TEXT DEFAULT '',
    reversal_reason TEXT NULL,
    reversed_at TIMESTAMPTZ NULL,
    reversed_by_user_id INTEGER NULL REFERENCES users(id),
    created_by_user_id INTEGER NOT NULL REFERENCES users(id),
    created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
);

-- 14. Payment Allocations (Settlement to Invoices)
CREATE TABLE IF NOT EXISTS payment_allocations (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    payment_id VARCHAR(64) NOT NULL REFERENCES payments(id) ON DELETE CASCADE,
    invoice_id VARCHAR(64) NOT NULL REFERENCES invoices(id),
    amount NUMERIC(12, 2) NOT NULL CHECK(amount > 0),
    status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE' CHECK(status IN ('ACTIVE', 'REVERSED')),
    notes TEXT DEFAULT '',
    allocated_by_user_id INTEGER NOT NULL REFERENCES users(id),
    allocated_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
);

